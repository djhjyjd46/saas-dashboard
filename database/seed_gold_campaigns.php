<?php
// Скрипт для массового добавления рекламных кампаний для темы Gold.
// Запуск: php artisan tinker database/seed_gold_campaigns.php

use App\Models\Tenant;

$data = [
    'общая' => ['707572867', '707572792', '707624776', '707934602', '707572848', '707572826', '707671020'],
    'инженерные специальности' => ['707946804', '707671968', '707672863'],
    'психологические специальности' => ['707946356', '707946332'],
    'медиа, дизайн и коммуникации' => ['707946509', '707946484', '707947391', '707947418'],
    'специальности киноиндустрии' => ['707946413', '707946431'],
    'туристические специальности' => ['707946935', '707946955'],
    'экономические специальности' => ['707946613', '707671703'],
    'юридические специальности' => ['707920939', '707920955', '707641938', '707670905'],
    'лингвистические специальности' => ['707947057', '707947025'],
    'информационные технологии' => ['708037267', '708037298'],
];

$tenant = Tenant::first();

if (!$tenant) {
    echo "Ошибка: Основной Tenant не найден в базе данных.\n";
    exit;
}

$settings = $tenant->settings ?? [];

$mapping = [];
$uiMapping = [];
$externalIds = [];

foreach ($data as $cat => $ids) {
    if (!empty($ids)) {
        $mapping[$cat] = $ids;
        $uiMapping[$cat] = implode(', ', $ids);
        $externalIds = array_merge($externalIds, $ids);
    }
}

$settings['category_mapping'] = $mapping;
$settings['category_mapping_ui'] = $uiMapping;
$settings['allowed_external_ids'] = array_unique($externalIds);

$tenant->settings = $settings;
$tenant->save();

echo "Успешно! " . count($externalIds) . " кампаний были распределены по " . count($mapping) . " категориям и сохранены в настройки Tenant.\n";
echo "Теперь вы можете зайти на дашборд Gold или в технические настройки, чтобы увидеть результат.\n";
